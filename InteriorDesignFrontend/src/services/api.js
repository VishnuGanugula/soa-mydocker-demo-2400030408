/**
 * LuxDesign Studio - API Client
 * Connects to Spring Boot backend running on port 2006
 * Controller: InterioirDesignController
 */

const API_BASE_URL = 'http://localhost:2007';

/**
 * Helper to execute fetch requests with consistent error handling
 */
async function request(endpoint, options = {}) {
  const url = `${API_BASE_URL}${endpoint}`;
  
  const headers = {
    'Accept': 'application/json',
    ...(options.body ? { 'Content-Type': 'application/json' } : {}),
    ...options.headers,
  };

  try {
    const response = await fetch(url, {
      ...options,
      headers,
    });

    // For delete or string responses:
    const contentType = response.headers.get('content-type') || '';
    let data;
    
    if (contentType.includes('application/json')) {
      data = await response.json();
    } else {
      data = await response.text();
    }

    if (!response.ok) {
      const errorMessage = typeof data === 'string' && data.length > 0 
        ? data 
        : data?.message || `Request failed with status: ${response.status}`;
      throw new Error(errorMessage);
    }

    return data;
  } catch (error) {
    if (error.name === 'TypeError' && error.message.includes('fetch')) {
      throw new Error('Could not connect to Spring Boot server at ' + API_BASE_URL + '. Please ensure the backend is running on port 2006.');
    }
    throw error;
  }
}

export const interiorDesignApi = {
  /**
   * Health check endpoint: GET /
   */
  checkHealth: async () => {
    return request('/', { method: 'GET' });
  },

  /**
   * Fetch all interior designs: GET /displayall
   */
  getAllDesigns: async () => {
    return request('/displayall', { method: 'GET' });
  },

  /**
   * Fetch single design by ID: GET /display/{id}
   */
  getDesignById: async (id) => {
    return request(`/display/${id}`, { method: 'GET' });
  },

  /**
   * Add new interior design: POST /add
   * NOTE: ID is auto-generated by DB and must NOT be sent.
   * payload: { projectName, clientName, budget, completed }
   */
  addDesign: async (designData) => {
    return request('/add', {
      method: 'POST',
      body: JSON.stringify({
        projectName: designData.projectName.trim(),
        clientName: designData.clientName.trim(),
        budget: parseFloat(designData.budget),
        completed: Boolean(designData.completed)
      }),
    });
  },

  /**
   * Update an existing design: PUT /update
   * payload: { id, budget, completed, projectName, clientName }
   */
  updateDesign: async (designData) => {
    return request('/update', {
      method: 'PUT',
      body: JSON.stringify({
        id: Number(designData.id),
        budget: parseFloat(designData.budget),
        completed: Boolean(designData.completed),
        projectName: designData.projectName,
        clientName: designData.clientName
      }),
    });
  },

  /**
   * Delete design by ID: DELETE /delete/{id}
   */
  deleteDesign: async (id) => {
    return request(`/delete/${id}`, {
      method: 'DELETE',
    });
  },
};
